const SelectLabel = React.forwardRef(({ className, ...props }, ref) => (
  <SelectPrimitive.Label
    ref={ref}
    className={cn("px-3 py-1.5 text-xs font-bold text-[#6F6E73] uppercase tracking-wider", className)}
    {...props} />
))
