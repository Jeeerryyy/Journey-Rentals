import * as React from "react"
import * as SelectPrimitive from "@radix-ui/react-select"
import { Check, ChevronDown, ChevronUp } from "lucide-react"

import { cn } from "@/lib/utils"

const Select = SelectPrimitive.Root

const SelectGroup = SelectPrimitive.Group

const SelectValue = SelectPrimitive.Value

const SelectTrigger = React.forwardRef(({ className, children, ...props }, ref) => (
  <SelectPrimitive.Trigger
    ref={ref}
    className={cn(
      "flex h-11 sm:h-12 w-full items-center justify-between whitespace-nowrap rounded-xl sm:rounded-2xl border border-[#DFDCE8] bg-[#F6F5FA] px-3.5 sm:px-4 py-2 text-xs sm:text-sm font-semibold text-[#212121] shadow-2xs placeholder:text-[#99989E] hover:border-[#212121]/50 focus:border-[#212121] focus:outline-none focus:ring-1 focus:ring-[#212121] disabled:cursor-not-allowed disabled:opacity-50 transition-all [&>span]:line-clamp-1 text-left cursor-pointer",
      className
    )}
    {...props}>
    {children}
    <SelectPrimitive.Icon asChild>
      <ChevronDown className="h-4 w-4 text-[#6F6E73] shrink-0 transition-transform duration-200" />
    </SelectPrimitive.Icon>
  </SelectPrimitive.Trigger>
))
